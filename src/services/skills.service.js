'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { exists, read, write } = require('../core/fs');
const { parseFrontmatter } = require('../core/frontmatter');
const { loadConfig } = require('../core/config');
const { detectProject, getPackageRunner } = require('../core/detector');
const {
  VERIFY_KINDS,
  classifyCommand,
  parseMakeTargets,
  parseJustRecipes,
  parseTaskfileTasks,
  parseWorkflowRuns,
  parseGitlabScripts
} = require('../core/commands');
const { findSecrets, formatSecretFinding } = require('./secrets.service');

const SKILLS_DIR = '.ai/skills';
const VERIFY_SKILL = 'rc-verify-change';
const SOURCE_MARKER = '<!-- repocanon:generated';
const COPY_MARKER = '<!-- Generated by RepoCanon from';
const MAX_PER_KIND = 4;
const KIND_LABELS = { check: 'All checks', format: 'Format', lint: 'Lint', typecheck: 'Typecheck', test: 'Test' };

/** Where each tool loads Agent Skills from. Cursor, Codex, Gemini CLI and Copilot share .agents/skills. */
const SKILL_DIRS = [
  { dir: '.claude/skills', tools: ['claude'] },
  { dir: '.agents/skills', tools: ['cursor', 'codex', 'gemini', 'copilot'] }
];

/**
 * Every command the repo itself uses to check a change, grouped by step, with where
 * each one was found. Entry points (scripts, make/just/task targets) come before raw
 * CI commands; a CI line that calls an entry point adds its source to that entry.
 *
 * @param {string} root - Project root directory
 * @returns {Array<{ kind: string, command: string, sources: string[], ci: boolean }>}
 */
function collectVerifyCommands(root) {
  const entries = [];
  const keyOf = command => command.trim().replace(/^(npm|pnpm|yarn|bun) run /, '$1 ');
  const add = (command, kind, source, ci = false) => {
    if (!kind) return;
    const key = keyOf(command);
    const existing = entries.find(e => keyOf(e.command) === key || (ci && key.startsWith(`${keyOf(e.command)} `)));
    if (existing) {
      if (!existing.sources.includes(source)) existing.sources.push(source);
      return;
    }
    entries.push({ kind, command, sources: [source], ci });
  };
  const readJson = rel => {
    try {
      return JSON.parse(read(path.join(root, rel)) || '{}');
    } catch {
      return {};
    }
  };

  const runScript = getPackageRunner(root);
  for (const name of Object.keys(readJson('package.json').scripts || {})) {
    add(runScript(name), classifyCommand(name), 'package.json');
  }
  for (const name of Object.keys(readJson('composer.json').scripts || {})) {
    add(`composer ${name}`, classifyCommand(name), 'composer.json');
  }
  const targetFiles = [
    ['Makefile', parseMakeTargets, 'make'],
    ['justfile', parseJustRecipes, 'just'],
    ['Justfile', parseJustRecipes, 'just'],
    ['Taskfile.yml', parseTaskfileTasks, 'task'],
    ['Taskfile.yaml', parseTaskfileTasks, 'task']
  ];
  for (const [file, parse, tool] of targetFiles) {
    const text = read(path.join(root, file));
    if (text === null) continue;
    for (const name of parse(text)) add(`${tool} ${name}`, classifyCommand(name), file);
  }

  const ciRuns = [];
  const workflowsDir = path.join(root, '.github', 'workflows');
  if (fs.existsSync(workflowsDir)) {
    for (const file of fs.readdirSync(workflowsDir).filter(f => /\.ya?ml$/.test(f)).sort()) {
      const runs = parseWorkflowRuns(read(path.join(workflowsDir, file)) || '');
      ciRuns.push(...runs.map(run => ({ ...run, file })));
    }
  }
  const gitlab = read(path.join(root, '.gitlab-ci.yml'));
  if (gitlab !== null) {
    ciRuns.push(...parseGitlabScripts(gitlab).map(run => ({ ...run, file: '.gitlab-ci.yml' })));
  }
  for (const run of ciRuns) {
    add(run.command, classifyCommand(run.command), `CI \`${run.file}\`${run.step ? ` › ${run.step}` : ''}`, true);
  }

  // Manifests without scripts (go.mod, Cargo.toml, pyproject…) still have a known test/lint command
  const detected = detectProject(root);
  for (const kind of ['lint', 'test']) {
    if (detected[kind] && detected[kind] !== 'TODO' && !entries.some(e => e.kind === kind)) {
      add(detected[kind], kind, 'project manifest');
    }
  }

  const rank = e => VERIFY_KINDS.indexOf(e.kind) * 2 + (e.ci ? 1 : 0);
  return entries
    .map((e, i) => ({ e, i }))
    .sort((a, b) => rank(a.e) - rank(b.e) || a.i - b.i)
    .map(({ e }) => e);
}

const hashOf = text => crypto.createHash('sha1').update(text).digest('hex').slice(0, 10);

/**
 * Splits a SKILL.md into frontmatter and body, dropping RepoCanon's marker lines.
 *
 * @param {string} text
 * @returns {{ frontmatter: string, body: string, sha: string|null }}
 */
function splitSkill(text) {
  const match = /^(---\r?\n[\s\S]*?\r?\n---)\r?\n?/.exec(text || '');
  const frontmatter = match ? match[1] : '';
  const rest = match ? text.slice(match[0].length) : text || '';
  const lines = rest.split('\n');
  const markerIndex = lines.findIndex(l => l.startsWith(SOURCE_MARKER) || l.startsWith(COPY_MARKER));
  const sha = markerIndex >= 0 ? (lines[markerIndex].match(/sha=([0-9a-f]+)/) || [])[1] || null : null;
  if (markerIndex >= 0) lines.splice(markerIndex, 1);
  return { frontmatter, body: lines.join('\n').replace(/^\n+/, ''), sha };
}

/**
 * The generated verify-a-change skill, or null when the repo shows no check commands.
 *
 * @param {string} root
 * @returns {string|null}
 */
function buildVerifySkill(root) {
  const entries = collectVerifyCommands(root);
  if (!entries.length) return null;

  const kinds = VERIFY_KINDS.filter(kind => entries.some(e => e.kind === kind));
  const describe = list => list.slice(0, MAX_PER_KIND).map(e => `\`${e.command}\` (${e.sources.join(' · ')})`).join('; ');
  const primaryOf = kind => {
    const all = entries.filter(e => e.kind === kind);
    return all.some(e => !e.ci) ? all.filter(e => !e.ci) : all;
  };
  const steps = [];
  const ciExtras = [];
  for (const kind of kinds.filter(k => k !== 'check')) {
    const primary = primaryOf(kind);
    ciExtras.push(...entries.filter(e => e.kind === kind && !primary.includes(e)));
    steps.push(`${steps.length + 1}. **${KIND_LABELS[kind]}:** ${describe(primary)}`);
  }
  // An aggregate target (make check) is the quick path; the steps say where a failure is
  const aggregate = kinds.includes('check') ? describe(primaryOf('check')) : '';
  const intro = aggregate
    ? (steps.length
      ? `Run ${aggregate} from the repository root before saying the change is done. If it fails, run the steps below one at a time to find the failing one, fix it, and run that step again.`
      : `Run ${aggregate} from the repository root before saying the change is done. If it fails, fix the cause and run it again.`)
    : 'Run these from the repository root, in order, before saying the change is done. Stop at the first failure, fix it, and run that step again.';

  const name = detectProject(root).name || path.basename(root);
  const stepNames = kinds.filter(k => k !== 'check').map(k => KIND_LABELS[k].toLowerCase());
  const stepList = stepNames.length > 1 ? `${stepNames.slice(0, -1).join(', ')} and ${stepNames.at(-1)}` : stepNames[0] || 'check';
  const sourceKinds = [...new Set(entries.flatMap(e => e.sources).map(s => (s.startsWith('CI') ? 'CI' : s)))];
  const description = `Use before saying a code change in ${name} is done: runs this repo's own ${stepList} commands ` +
    `(from ${sourceKinds.join(', ')}) in the order to run them, and says what to do when one fails.`;

  const body = [
    '# Verify a change',
    '',
    intro,
    '',
    ...(steps.length ? [...steps, ''] : []),
    ...(ciExtras.length ? [`CI also runs: ${ciExtras.slice(0, 6).map(e => `\`${e.command}\``).join(', ')}.`, ''] : []),
    '- If a command needs a service, database or environment variable you don\'t have, say so in your answer instead of skipping the step silently.',
    '- Don\'t weaken a test or a lint rule to make a step pass; fix the code, or explain why the check is wrong.',
    ''
  ].join('\n');

  const frontmatter = `---\nname: ${VERIFY_SKILL}\ndescription: ${JSON.stringify(description)}\n---`;
  const sha = hashOf(`${frontmatter}\n${body}`);
  return `${frontmatter}\n${SOURCE_MARKER} sha=${sha} — once you edit this file RepoCanon stops updating it -->\n\n${body}`;
}

/**
 * Agent Skills spec checks, plus secrets: a skill is copied into tool folders that
 * are committed and shared.
 *
 * @param {string} text - SKILL.md content
 * @param {string} folder - the skill's folder name
 * @returns {string[]} problems (empty when valid)
 */
function validateSkill(text, folder) {
  const problems = [];
  const fm = parseFrontmatter(text);
  const unquote = value => String(value || '').replace(/^(['"])(.*)\1$/, '$2');
  const name = unquote(fm.name);
  const description = unquote(fm.description);
  if (!name) {
    problems.push('frontmatter name missing');
  } else if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name) || name.length > 64) {
    problems.push(`name "${name}" must be lowercase letters, digits and single hyphens, max 64 characters`);
  } else if (name !== folder) {
    problems.push(`name "${name}" must match its folder "${folder}"`);
  }
  if (!description) {
    problems.push('frontmatter description missing — say what the skill does and when to use it');
  } else if (description.length > 1024) {
    problems.push(`description is ${description.length} characters (max 1024)`);
  }
  for (const finding of findSecrets(text)) {
    problems.push(formatSecretFinding(`${SKILLS_DIR}/${folder}/SKILL.md`, finding));
  }
  return problems;
}

/**
 * Skill folders under .ai/skills that hold a SKILL.md.
 *
 * @param {string} root
 * @returns {string[]}
 */
function listSourceSkills(root) {
  const dir = path.join(root, SKILLS_DIR);
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir)
    .filter(name => exists(path.join(dir, name, 'SKILL.md')))
    .sort();
}

/**
 * Copies RepoCanon wrote into a tool's skills folder.
 *
 * @param {string} root
 * @param {string} dir
 * @returns {string[]} repo-relative SKILL.md paths
 */
function listGeneratedCopies(root, dir) {
  const full = path.join(root, dir);
  if (!fs.existsSync(full)) return [];
  return fs.readdirSync(full)
    .map(name => `${dir}/${name}/SKILL.md`)
    .filter(rel => (read(path.join(root, rel)) || '').includes(COPY_MARKER));
}

/**
 * The skills the project should have, compared with what's on disk:
 * the generated source in .ai/skills (kept once a person edits it) and a copy per tool folder.
 *
 * @param {string} root - Project root directory
 * @returns {Array<{ file: string, action: 'create'|'update'|'unchanged'|'remove'|'kept'|'conflict'|'invalid', skill: string|null, kind: 'source'|'copy', content?: string, reason?: string }>}
 */
function planSkills(root) {
  const rows = [];
  const config = loadConfig(root);
  const targets = Array.isArray(config.targets) ? config.targets : [];
  const sources = new Map();

  // The generated source: regenerate only while it still matches what RepoCanon wrote
  const verifyRel = `${SKILLS_DIR}/${VERIFY_SKILL}/SKILL.md`;
  const current = read(path.join(root, verifyRel));
  const generated = buildVerifySkill(root);
  const untouched = current !== null && (() => {
    const { frontmatter, body, sha } = splitSkill(current);
    return Boolean(sha) && hashOf(`${frontmatter}\n${body}`) === sha;
  })();
  if (current === null) {
    if (generated) rows.push({ file: verifyRel, action: 'create', skill: VERIFY_SKILL, kind: 'source', content: generated });
  } else if (!untouched) {
    rows.push({ file: verifyRel, action: 'kept', skill: VERIFY_SKILL, kind: 'source', reason: 'edited by you — RepoCanon no longer updates it' });
  } else if (!generated) {
    rows.push({ file: verifyRel, action: 'remove', skill: VERIFY_SKILL, kind: 'source' });
  } else {
    rows.push({ file: verifyRel, action: current === generated ? 'unchanged' : 'update', skill: VERIFY_SKILL, kind: 'source', content: generated });
  }

  const pendingSource = rows.find(r => r.kind === 'source' && r.content && r.action !== 'remove');
  const removedSource = rows.some(r => r.kind === 'source' && r.action === 'remove');
  for (const folder of listSourceSkills(root)) {
    if (folder === VERIFY_SKILL && removedSource) continue;
    const rel = `${SKILLS_DIR}/${folder}/SKILL.md`;
    sources.set(folder, folder === VERIFY_SKILL && pendingSource ? pendingSource.content : read(path.join(root, rel)));
  }
  if (pendingSource && !sources.has(VERIFY_SKILL)) sources.set(VERIFY_SKILL, pendingSource.content);

  const valid = new Map();
  for (const [folder, text] of sources) {
    const problems = validateSkill(text, folder);
    if (problems.length) {
      rows.push({ file: `${SKILLS_DIR}/${folder}/SKILL.md`, action: 'invalid', skill: folder, kind: 'source', reason: problems.join('; ') });
    } else {
      valid.set(folder, text);
    }
  }

  for (const { dir, tools } of SKILL_DIRS) {
    const wanted = new Set();
    if (tools.some(tool => targets.includes(tool))) {
      for (const [folder, text] of valid) {
        const file = `${dir}/${folder}/SKILL.md`;
        const { frontmatter, body } = splitSkill(text);
        const content = `${frontmatter}\n${COPY_MARKER} ${SKILLS_DIR}/${folder}/SKILL.md — edit that file, then run: npx repocanon skills -->\n\n${body}`;
        const existing = read(path.join(root, file));
        wanted.add(file);
        if (existing === null) {
          rows.push({ file, action: 'create', skill: folder, kind: 'copy', content });
        } else if (!existing.includes(COPY_MARKER)) {
          rows.push({ file, action: 'conflict', skill: folder, kind: 'copy', reason: 'a skill of the same name already exists and is not RepoCanon\'s — left alone' });
        } else {
          rows.push({ file, action: existing === content ? 'unchanged' : 'update', skill: folder, kind: 'copy', content });
        }
      }
    }
    for (const file of listGeneratedCopies(root, dir)) {
      if (!wanted.has(file)) rows.push({ file, action: 'remove', skill: null, kind: 'copy' });
    }
  }

  return rows;
}

/**
 * Writes or removes what planSkills() found out of date. Kept, conflicting and
 * invalid skills are never touched.
 *
 * @param {string} root
 * @param {ReturnType<typeof planSkills>} plan
 * @returns {ReturnType<typeof planSkills>}
 */
function applySkills(root, plan) {
  for (const row of plan) {
    const fullPath = path.join(root, row.file);
    if (row.action === 'create' || row.action === 'update') {
      write(fullPath, row.content);
    } else if (row.action === 'remove') {
      fs.unlinkSync(fullPath);
      try {
        fs.rmdirSync(path.dirname(fullPath));
      } catch {
        // Folder still holds other files: keep it
      }
    }
  }
  return plan;
}

/**
 * @param {ReturnType<typeof planSkills>} plan
 * @returns {ReturnType<typeof planSkills>} rows that would change a file
 */
function getPendingSkills(plan) {
  return plan.filter(row => row.action === 'create' || row.action === 'update' || row.action === 'remove');
}

/**
 * @param {ReturnType<typeof planSkills>} plan
 * @returns {ReturnType<typeof planSkills>} conflicts and invalid skills, which need a person
 */
function getSkillProblems(plan) {
  return plan.filter(row => row.action === 'conflict' || row.action === 'invalid');
}

module.exports = {
  collectVerifyCommands,
  buildVerifySkill,
  validateSkill,
  planSkills,
  applySkills,
  getPendingSkills,
  getSkillProblems,
  VERIFY_SKILL,
  SKILL_DIRS
};
