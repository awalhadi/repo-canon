'use strict';

const fs = require('fs');
const path = require('path');
const { exists, read, write, listWorkspaceFiles } = require('../core/fs');
const { stripFrontmatter } = require('../core/frontmatter');
const { loadConfig } = require('../core/config');
const { readManagedBlock, upsertManagedBlock, removeManagedBlock } = require('../core/blocks');
const { getKnowledgeDocs } = require('./status.service');

const TEMPLATES_DIR = path.resolve(__dirname, '../../templates');
const GENERATED_MARKER = '<!-- Generated by RepoCanon from';
const NESTED_MARKER = 'RepoCanon module';

/**
 * Scoped-rule writers per tool: where each module's rule file goes and how it says
 * which files it applies to.
 */
const WRITERS = {
  cursor: {
    dir: '.cursor/rules',
    fileName: slug => `rc-${slug}.mdc`,
    frontmatter: (globs, description) =>
      `---\ndescription: ${JSON.stringify(description)}\nglobs: ${globs.join(',')}\nalwaysApply: false\n---\n`
  },
  copilot: {
    dir: '.github/instructions',
    fileName: slug => `rc-${slug}.instructions.md`,
    frontmatter: globs => `---\napplyTo: ${JSON.stringify(globs.join(','))}\n---\n`
  }
};

/**
 * Lines of the module template that are placeholders, not knowledge.
 *
 * @returns {Set<string>}
 */
function getTemplateLines() {
  const template = stripFrontmatter(read(path.join(TEMPLATES_DIR, 'module.md')) || '');
  return new Set(template.split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('#')));
}

/**
 * A doc still made only of template placeholders has nothing worth loading.
 *
 * @param {string} body
 * @param {Set<string>} templateLines
 * @returns {boolean}
 */
function isFilled(body, templateLines) {
  return body
    .split('\n')
    .map(l => l.trim())
    .some(l => l && !l.startsWith('#') && !templateLines.has(l) && !/^TODO\b/i.test(l.replace(/^[-*]\s*/, '')));
}

/**
 * code_paths → globs: a folder covers everything under it, a file covers itself.
 *
 * @param {string} root
 * @param {string[]} codePaths
 * @returns {string[]}
 */
function toGlobs(root, codePaths) {
  return codePaths.map(p => {
    const clean = p.replace(/^\.\//, '');
    if (clean.endsWith('/')) return `${clean}**`;
    try {
      if (fs.statSync(path.join(root, clean)).isDirectory()) return `${clean}/**`;
    } catch {
      // Missing path: treat as written
    }
    return clean;
  });
}

/**
 * First line of the doc's "Purpose" section, for tools that show a rule description.
 *
 * @param {string} body
 * @param {string} slug
 * @returns {string}
 */
function getPurpose(body, slug) {
  const lines = body.split('\n');
  const start = lines.findIndex(l => /^##\s+purpose\b/i.test(l.trim()));
  const first = start === -1 ? null : lines.slice(start + 1).find(l => l.trim() && !l.startsWith('#'));
  return first ? first.trim().replace(/^[-*]\s*/, '') : `Rules and gotchas for the ${slug} module`;
}

/**
 * Filled module docs with their code paths, as the rule writers need them.
 *
 * @param {string} root
 * @returns {Array<{ slug: string, rel: string, body: string, codePaths: string[] }>}
 */
function getRuleSources(root) {
  const templateLines = getTemplateLines();
  return getKnowledgeDocs(root)
    .filter(doc => doc.rel.startsWith('.ai/modules/'))
    .map(doc => {
      const body = stripFrontmatter(doc.text)
        .split('\n')
        .filter(l => !templateLines.has(l.trim()) || !l.trim().startsWith('>'))
        .join('\n')
        .trim();
      return {
        slug: path.posix.basename(doc.rel, '.md'),
        rel: doc.rel,
        body,
        codePaths: Array.isArray(doc.fm.code_paths) ? doc.fm.code_paths : [],
        filled: isFilled(body, templateLines)
      };
    })
    .filter(source => source.filled && source.codePaths.length);
}

/**
 * Generated rule files currently on disk (ours only: they carry the generated header).
 *
 * @param {string} root
 * @param {{ dir: string }} writer
 * @returns {string[]} repo-relative paths
 */
function listGeneratedFiles(root, writer) {
  const dir = path.join(root, writer.dir);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter(name => name.startsWith('rc-'))
    .map(name => `${writer.dir}/${name}`)
    .filter(rel => (read(path.join(root, rel)) || '').includes(GENERATED_MARKER));
}

/**
 * Nested AGENTS.md files holding a RepoCanon module pointer.
 *
 * @param {string} root
 * @returns {string[]}
 */
function listNestedPointers(root) {
  return listWorkspaceFiles(root)
    .filter(rel => rel !== 'AGENTS.md' && path.posix.basename(rel) === 'AGENTS.md')
    .filter(rel => (readManagedBlock(path.join(root, rel)) || '').includes(NESTED_MARKER));
}

/**
 * Computes the scoped rule files the project should have, compared with what's on disk.
 *
 * @param {string} root - Project root directory
 * @returns {Array<{ file: string, action: 'create'|'update'|'unchanged'|'remove', module: string|null, kind: 'file'|'nested', content?: string }>}
 */
function planRules(root) {
  const config = loadConfig(root);
  const targets = Array.isArray(config.targets) ? config.targets : [];
  const sources = getRuleSources(root);
  const rows = [];

  const compare = (file, content, module, kind) => {
    const fullPath = path.join(root, file);
    const current = kind === 'nested' ? readManagedBlock(fullPath) : read(fullPath);
    const action = !exists(fullPath) ? 'create' : current === content ? 'unchanged' : 'update';
    rows.push({ file, action, module, kind, content });
  };

  for (const [toolId, writer] of Object.entries(WRITERS)) {
    const wanted = new Set();
    if (targets.includes(toolId)) {
      for (const source of sources) {
        const file = `${writer.dir}/${writer.fileName(source.slug)}`;
        const header = `${GENERATED_MARKER} ${source.rel} — edit that file, then run: npx repocanon rules -->`;
        const content = `${writer.frontmatter(toGlobs(root, source.codePaths), getPurpose(source.body, source.slug))}${header}\n\n${source.body}\n`;
        wanted.add(file);
        compare(file, content, source.slug, 'file');
      }
    }
    for (const file of listGeneratedFiles(root, writer)) {
      if (!wanted.has(file)) rows.push({ file, action: 'remove', module: null, kind: 'file' });
    }
  }

  const wantedNested = new Set();
  if (config.nestedAgents === true) {
    for (const source of sources) {
      for (const codePath of source.codePaths) {
        const dir = codePath.replace(/^\.\//, '').replace(/\/$/, '');
        let isDir = false;
        try {
          isDir = Boolean(dir) && fs.statSync(path.join(root, dir)).isDirectory();
        } catch {
          // Missing path: skip
        }
        if (!isDir) continue;
        const file = `${dir}/AGENTS.md`;
        if (wantedNested.has(file)) continue;
        wantedNested.add(file);
        compare(file, `${NESTED_MARKER} \`${source.slug}\`: its rules, invariants and gotchas are in \`${source.rel}\` — read it before changing code in this folder.`, source.slug, 'nested');
      }
    }
  }
  for (const file of listNestedPointers(root)) {
    if (!wantedNested.has(file)) rows.push({ file, action: 'remove', module: null, kind: 'nested' });
  }

  return rows;
}

/**
 * Writes or removes what planRules() found out of date.
 *
 * @param {string} root
 * @param {ReturnType<typeof planRules>} plan
 * @returns {ReturnType<typeof planRules>}
 */
function applyRules(root, plan) {
  for (const row of plan) {
    const fullPath = path.join(root, row.file);
    if (row.action === 'create' || row.action === 'update') {
      if (row.kind === 'nested') {
        upsertManagedBlock(fullPath, row.content);
      } else {
        write(fullPath, row.content);
      }
    } else if (row.action === 'remove') {
      if (row.kind === 'nested') {
        removeManagedBlock(fullPath);
      } else {
        fs.unlinkSync(fullPath);
      }
    }
  }
  return plan;
}

/**
 * @param {ReturnType<typeof planRules>} plan
 * @returns {Array<ReturnType<typeof planRules>[number]>} rows that would change something
 */
function getPendingRules(plan) {
  return plan.filter(row => row.action !== 'unchanged');
}

module.exports = {
  planRules,
  applyRules,
  getPendingRules,
  toGlobs,
  GENERATED_MARKER
};
