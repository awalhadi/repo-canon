'use strict';

const crypto = require('crypto');
const { toSlug } = require('./fs');

/**
 * A claim is a rule bullet that says how it can be checked:
 *   - Money is integer cents. <!-- rc: anchor=src/money.js#toCents -->
 *   - Floats are rejected. <!-- rc: test=test/money.test.js#rejects floats -->
 * Keys are separated by ";": anchor, test, id. Everything else about a claim (its hash,
 * its state) is computed by the tool, never written by hand.
 */
const ANNOTATION = /<!--\s*rc:\s*(.*?)\s*-->/;
const CLAIM_KEYS = new Set(['anchor', 'test', 'id']);
const LOCK_FILE = '.ai/canon.lock';
const LOCK_HEADER = '# Generated by `repocanon stamp`: the code each claim was checked against. Do not edit.';

/**
 * Splits `path#rest` into its parts; `rest` may be empty.
 *
 * @param {string} value
 * @returns {{ path: string, name: string }}
 */
function splitRef(value) {
  const hash = value.indexOf('#');
  return hash === -1
    ? { path: value.trim(), name: '' }
    : { path: value.slice(0, hash).trim(), name: value.slice(hash + 1).trim() };
}

/**
 * The claims in one doc. Bullets without an `rc:` annotation are not claims.
 *
 * @param {string} text
 * @param {string} docName - e.g. "billing" or "CONVENTIONS", the default id prefix
 * @returns {Array<{ id: string, line: number, text: string, anchor: { path: string, name: string }|null, test: { path: string, name: string }|null, problems: string[] }>}
 */
function parseClaims(text, docName) {
  const claims = [];
  String(text || '').split('\n').forEach((line, index) => {
    if (!/^\s*[-*] /.test(line)) return;
    const match = line.match(ANNOTATION);
    if (!match) return;

    const fields = {};
    const problems = [];
    for (const part of match[1].split(';').map(p => p.trim()).filter(Boolean)) {
      const eq = part.indexOf('=');
      const key = eq === -1 ? part : part.slice(0, eq).trim();
      if (!CLAIM_KEYS.has(key) || eq === -1) {
        problems.push(`unknown annotation "${part}" (use anchor=path#symbol, test=path#name, id=name)`);
        continue;
      }
      fields[key] = part.slice(eq + 1).trim();
    }

    const claimText = line.replace(ANNOTATION, '').replace(/^\s*[-*] /, '').trim();
    const base = fields.id || claimText.split(/\s+/).slice(0, 6).join(' ');
    claims.push({
      id: `${docName}/${toSlug(base) || `line-${index + 1}`}`,
      line: index + 1,
      text: claimText,
      anchor: fields.anchor ? splitRef(fields.anchor) : null,
      test: fields.test ? splitRef(fields.test) : null,
      problems
    });
  });
  return claims;
}

/**
 * Definition patterns for a symbol across the common stacks: JS/TS, Python, Go,
 * Rust, PHP, Java/C#/Kotlin-style methods and class members.
 *
 * @param {string} name
 * @returns {RegExp[]}
 */
function getDefinitionPatterns(name) {
  const n = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const mods = '(?:(?:export|default|public|private|protected|internal|static|final|abstract|async|override|readonly|pub(?:\\([^)]*\\))?|unsafe|const|open|sealed|virtual)\\s+)*';
  // A method header looks like a call ("toCents(x)"), so those patterns also refuse
  // statements: a leading keyword, or a line ending in ";" or ",".
  const notStatement = '(?!(?:return|await|new|throw|yield|if|else|elif|while|for|switch|case|typeof|echo|print|assert|raise)\\b)';
  const noTerminator = '(?!.*[;,]\\s*$)';
  return [
    new RegExp(`^\\s*${mods}(?:function\\*?|def|fn|func|class|interface|trait|struct|enum|type|impl|module|record|object)\\s+${n}\\b`),
    new RegExp(`^\\s*func\\s+\\([^)]*\\)\\s*${n}\\b`),
    new RegExp(`^\\s*${mods}(?:const|let|var|val)\\s+${n}\\b`),
    new RegExp(`^\\s*${noTerminator}${notStatement}${mods}(?:get\\s+|set\\s+)?${n}\\s*(?:<[^>]*>)?\\s*\\(`),
    new RegExp(`^\\s*${noTerminator}${notStatement}${mods}[\\w<>\\[\\],.?]+(?:\\s+[\\w<>\\[\\],.?]+)*\\s+${n}\\s*\\(`),
    new RegExp(`^\\s*${n}\\s*[:=]\\s*(?:async\\s*)?(?:function\\b|\\(|[\\w$]+\\s*=>)`),
    // Module-level assignment, unindented: Python/Ruby constants (`RATE_LIMITED = 'x'`, `MAX: int = 5`)
    new RegExp(`^${n}\\s*(?::\\s*[\\w\\[\\], .|]+)?\\s*=(?!=)`)
  ];
}

/**
 * @param {string} line
 * @returns {number}
 */
function getIndent(line) {
  return line.match(/^\s*/)[0].replace(/\t/g, '    ').length;
}

/**
 * The lines of a symbol's definition: from the line that defines it to the line
 * where the indentation returns to its level (a closing brace or `end` is included).
 * `Outer.inner` looks for `inner` inside `Outer`.
 *
 * @param {string} source
 * @param {string} symbol
 * @param {number} [from=0]
 * @param {number} [to]
 * @returns {{ start: number, end: number }|null} 0-based, inclusive
 */
function locateSymbol(source, symbol, from = 0, to) {
  const lines = String(source || '').split('\n');
  const last = to === undefined ? lines.length - 1 : to;
  const [head, ...rest] = String(symbol || '').split('.');
  if (!head) return null;

  const patterns = getDefinitionPatterns(head);
  let start = -1;
  for (let i = from; i <= last && start === -1; i++) {
    if (patterns.some(re => re.test(lines[i]))) start = i;
  }
  if (start === -1) return null;

  const indent = getIndent(lines[start]);
  let end = start;
  for (let i = start + 1; i <= last; i++) {
    if (!lines[i].trim()) continue;
    // A brace on its own line at the header's level opens the body (PHP, C#, Allman style)
    if (getIndent(lines[i]) <= indent && /^\s*\{\s*$/.test(lines[i]) && end === i - 1) {
      end = i;
      continue;
    }
    if (getIndent(lines[i]) <= indent) {
      if (/^\s*(?:[}\])]+[;,)]*|end|fi|done)\s*$/.test(lines[i])) end = i;
      break;
    }
    end = i;
  }
  const region = { start, end };
  return rest.length ? locateSymbol(source, rest.join('.'), start + 1, end) : region;
}

/**
 * Hash of a region with formatting ignored: runs of whitespace collapsed, blank lines
 * dropped. A reformat leaves it unchanged; a changed condition or constant does not.
 *
 * @param {string} source
 * @param {{ start: number, end: number }} region
 * @returns {string} 12 hex characters
 */
function hashRegion(source, region) {
  const body = String(source).split('\n').slice(region.start, region.end + 1)
    .map(l => l.trim().replace(/\s+/g, ' '))
    .filter(Boolean)
    .join('\n');
  return crypto.createHash('sha1').update(body).digest('hex').slice(0, 12);
}

/**
 * @param {{ path: string, name: string }} anchor
 * @returns {string} "path#name" or "path"
 */
function formatRef(anchor) {
  return anchor.name ? `${anchor.path}#${anchor.name}` : anchor.path;
}

/**
 * @param {string|null} text - contents of .ai/canon.lock
 * @returns {Map<string, { anchor: string, hash: string }>}
 */
function parseLock(text) {
  const entries = new Map();
  for (const line of String(text || '').split('\n')) {
    if (!line.trim() || line.startsWith('#')) continue;
    const [id, anchor, hash] = line.split('\t');
    if (id && anchor && hash) entries.set(id, { anchor, hash });
  }
  return entries;
}

/**
 * Sorted, one line per claim, so two branches locking different claims rarely touch
 * the same lines.
 *
 * @param {Map<string, { anchor: string, hash: string }>} entries
 * @returns {string}
 */
function renderLock(entries) {
  const lines = [...entries].sort(([a], [b]) => a.localeCompare(b)).map(([id, e]) => `${id}\t${e.anchor}\t${e.hash}`);
  return `${[LOCK_HEADER, ...lines].join('\n')}\n`;
}

module.exports = {
  LOCK_FILE,
  ANNOTATION,
  parseClaims,
  locateSymbol,
  hashRegion,
  formatRef,
  parseLock,
  renderLock
};
